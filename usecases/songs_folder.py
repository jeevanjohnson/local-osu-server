def ms_to_ar(ms: float) -> float:
    if ms > 1200.0:
        return (1800.0 - ms) / 120.0

    return 5.0 + (1200.0 - ms) / 150.0


def ar_to_ms(ar: float) -> float:
    if ar < 5.0:
        return 1800.0 - 120.0 * ar

    return 1200.0 - 150.0 * (ar - 5.0)


def effective_ar_with_rate(rate: float, ar: float) -> float:
    if rate <= 0:
        return ar

    return ms_to_ar(ar_to_ms(ar) / rate)


def effective_od_with_rate(rate: float, od: float) -> float:
    if rate <= 0:
        return od

    od300_ms = 80.0 - 6.0 * od
    return (80.0 - (od300_ms / rate)) / 6.0


