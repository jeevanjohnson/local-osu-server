import base64
import binascii
from datetime import datetime
from pathlib import Path
from typing import Annotated, TypedDict

from jays_tools import MigratableModel
from pydantic import AfterValidator, Field, field_serializer, field_validator

from osuProtocol.client_web import osuMapStatus
from osuProtocol.server_packets import osuGameMode


def is_valid_status_for_saving(status: osuMapStatus) -> osuMapStatus:
    if status not in {osuMapStatus.RANKED, osuMapStatus.APPROVED, osuMapStatus.LOVED}:
        raise ValueError(f"Invalid status for saving: {status}")

    return status


class BeatmapV1(MigratableModel):
    time_inserted: datetime

    id: int
    set_id: int
    md5: str
    artist: str
    title: str
    difficulty_name: str
    max_combo: int
    status: Annotated[osuMapStatus, AfterValidator(is_valid_status_for_saving)]
    mode: osuGameMode
    difficulty_adjusted: bool  # if map was generated by osu!trainer

    osu_file_content: bytes | None = Field(default=None)
    # Just in case something goes wrong with the osu!trainer generated file,
    # we can keep the original one as a backup so replay is still playable.
    audio_file_content: bytes | None = Field(default=None)
    # TODO: could take up space quick?
    # TODO: Compression?

    @field_serializer("osu_file_content", "audio_file_content")
    def serialize_binary_fields(self, value: bytes | None) -> str | None:
        if value is None:
            return None

        return base64.b64encode(value).decode("ascii")

    @field_validator("osu_file_content", "audio_file_content", mode="before")
    @classmethod
    def deserialize_binary_fields(cls, value: object) -> bytes | None:
        if value is None:
            return None

        if isinstance(value, (bytes, bytearray, memoryview)):
            return value

        if not isinstance(value, str):
            raise TypeError(f"Unsupported binary field type: {type(value)!r}")

        try:
            return base64.b64decode(value.encode("ascii"), validate=True)
        except (ValueError, binascii.Error):
            # Backward compatibility for legacy JSON where bytes were dumped as text.
            return value.encode("utf-8")

    @property
    def can_display_pp(self) -> bool:
        return self.status in {osuMapStatus.RANKED, osuMapStatus.APPROVED}


CurrentBeatmap = BeatmapV1


class BeatmapSetV1(MigratableModel):
    id: int
    maps: list[CurrentBeatmap]
    path: Path | None = Field(default=None)


CurrentBeatmapSet = BeatmapSetV1


class Beatmaps(TypedDict):
    by_md5: dict[str, CurrentBeatmap]
    by_id: dict[int, CurrentBeatmap]
    by_set_id: dict[int, CurrentBeatmapSet]


def init_beatmaps() -> Beatmaps:
    return {"by_md5": {}, "by_id": {}, "by_set_id": {}}


class BeatmapsV1(MigratableModel):
    all: Beatmaps = Field(default_factory=init_beatmaps)


CurrentBeatmaps = BeatmapsV1
